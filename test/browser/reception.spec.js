import { test, expect } from '@playwright/test';

test('Japanese reception, curved sofa and lantern bridge render and staff can visit on mobile', async ({ page }) => {
  test.setTimeout(60000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('https://www.youtube-nocookie.com/**', route => route.fulfill({ contentType: 'text/html', body: '<p>YouTube fixture</p>' }));
  await page.goto('/');
  await expect(page.locator('#office-canvas canvas')).toBeVisible();
  await page.getByRole('button', { name: 'Sảnh tiếp đón', exact: true }).click();
  await expect(page.locator('#zone-detail')).toContainText('Sofa cong');
  await page.waitForTimeout(600);
  await page.locator('.office-panel').screenshot({ path: '/tmp/atelier-reception.png' });
  await page.getByRole('button', { name: 'Xem cửa đón khách', exact: true }).click();
  await expect(page.locator('#zone-detail')).toContainText('Sân ngoài');
  await page.waitForTimeout(600);
  await page.locator('.office-panel').screenshot({ path: '/tmp/atelier-guest-entrance.png' });
  await page.getByRole('button', { name: 'Quầy & mèo thần tài', exact: true }).click();
  await expect(page.locator('#zone-detail')).toContainText('Mèo thần tài');
  await page.waitForTimeout(600);
  await page.locator('.office-panel').screenshot({ path: '/tmp/atelier-front-desk.png' });
  const first = await page.locator('#office-canvas canvas').screenshot();
  await page.waitForTimeout(800);
  expect((await page.locator('#office-canvas canvas').screenshot()).equals(first)).toBe(false);
  await page.getByRole('button', { name: 'Cầu đèn lồng', exact: true }).click();
  await expect(page.locator('#zone-detail')).toContainText('treo đèn lồng');
  await page.waitForTimeout(600);
  await page.locator('.office-panel').screenshot({ path: '/tmp/atelier-reception-bridge.png' });
  await page.getByRole('button', { name: 'Ra sảnh tiếp khách', exact: true }).click();
  await expect(page.locator('[data-zone="reception"]')).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.agent-label[data-activity="walking"]').first()).toBeAttached();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Xem sảnh & sofa', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Chuyển động: bật', exact: true }).click();
  await page.getByRole('button', { name: 'Ra sảnh tiếp khách', exact: true }).click();
  await expect(page.locator('.agent-label[data-activity="walking"]')).toHaveCount(0);
  expect(errors).toEqual([]);
});
